-- El comprobante representa la MISMA operación. No se reemplazan precios
-- históricos por el precio de referencia ni fechas desconocidas por la fecha actual.
-- Regla del sistema simulado: descuento vacío significa que no hubo descuento.
UPDATE pedidos SET
 fecha_pedido = COALESCE(fecha_pedido, fecha_comprobante),
 precio_unitario = COALESCE(precio_unitario, precio_unitario_comprobante),
 descuento = COALESCE(descuento, 0);
ALTER TABLE pedidos ALTER COLUMN descuento SET NOT NULL;

-- Vista común: asegura que las cinco preguntas usen la misma población.
-- Los pedidos sin respaldo se conservan para revisión, pero no aportan ventas.
CREATE VIEW ventas_validas AS
SELECT id_pedido, id_cliente, id_producto, fecha_pedido, cantidad,
 precio_unitario, costo_unitario, descuento, canal,
 ROUND(cantidad * precio_unitario * (1 - descuento), 2) AS venta_neta,
 ROUND(cantidad * costo_unitario, 2) AS costo_total
FROM pedidos
WHERE estado = 'Completado'
 AND fecha_pedido IS NOT NULL AND precio_unitario IS NOT NULL;

-- CONTROL POSTERIOR: categorías mutuamente excluyentes que deben sumar 1000.
SELECT COUNT(*) AS total,
 COUNT(*) FILTER (WHERE estado <> 'Completado') AS no_completados,
 COUNT(*) FILTER (WHERE estado = 'Completado' AND
  (fecha_pedido IS NULL OR precio_unitario IS NULL)) AS completados_incompletos,
 COUNT(*) FILTER (WHERE estado = 'Completado' AND
  fecha_pedido IS NOT NULL AND precio_unitario IS NOT NULL) AS aptos_analisis,
 COUNT(*) FILTER (WHERE fecha_pedido IS NULL) AS fechas_a_revisar,
 COUNT(*) FILTER (WHERE precio_unitario IS NULL) AS precios_a_revisar
FROM pedidos;
COMMIT;

