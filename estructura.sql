CREATE TABLE clientes (
 id_cliente INTEGER PRIMARY KEY,
 nombre VARCHAR(80) NOT NULL,
 provincia VARCHAR(40) NOT NULL,
 ciudad VARCHAR(40) NOT NULL,
 tipo_cliente VARCHAR(15) NOT NULL CHECK (tipo_cliente IN ('Particular','Empresa'))
);
CREATE TABLE productos (
 id_producto INTEGER PRIMARY KEY,
 marca VARCHAR(30) NOT NULL,
 modelo VARCHAR(40) NOT NULL,
 segmento VARCHAR(20) NOT NULL,
 combustible VARCHAR(15) NOT NULL,
 transmision VARCHAR(15) NOT NULL,
 precio_referencia NUMERIC(12,2) NOT NULL CHECK (precio_referencia > 0),
 UNIQUE(marca, modelo)
);
CREATE TABLE pedidos (
 id_pedido INTEGER PRIMARY KEY,
 id_cliente INTEGER NOT NULL REFERENCES clientes(id_cliente),
 id_producto INTEGER NOT NULL REFERENCES productos(id_producto),
 fecha_pedido DATE,
 fecha_comprobante DATE,
 cantidad INTEGER NOT NULL CHECK (cantidad > 0),
 precio_unitario NUMERIC(12,2) CHECK (precio_unitario > 0),
 precio_unitario_comprobante NUMERIC(12,2) CHECK (precio_unitario_comprobante > 0),
 costo_unitario NUMERIC(12,2) NOT NULL CHECK (costo_unitario > 0),
 descuento NUMERIC(5,4) CHECK (descuento BETWEEN 0 AND 1),
 canal VARCHAR(20) NOT NULL,
 estado VARCHAR(15) NOT NULL CHECK (estado IN ('Completado','Cancelado','Pendiente'))
);
